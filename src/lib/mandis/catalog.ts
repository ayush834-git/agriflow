export type MandiFilterOptions = {
  state?: string | null;
  nearDistrict?: string | null;
  radiusKm?: number | null;
  commodity?: string | null;
};

/**
 * Returns mandis filtered by state and radius, and calculates distance to reference district.
 */
export function getMandis({
  state,
  nearDistrict = "Kurnool",
  radiusKm,
}: MandiFilterOptions = {}): (MandiMarket & { distanceKm: number })[] {
  const origin = (nearDistrict && DISTRICT_COORDINATES[nearDistrict]) || DISTRICT_COORDINATES["Kurnool"];

  let list = VERIFIED_MANDI_MARKETS;

  if (state && state.toLowerCase() !== "all" && state.toLowerCase() !== "all states") {
    list = list.filter((m) => m.state.toLowerCase() === state.toLowerCase());
  }

  const withDistances = list.map((m) => {
    const distanceKm = origin
      ? Math.round(haversineKm(origin.lat, origin.lng, m.lat, m.lng))
      : 0;

    return {
      ...m,
      distanceKm,
    };
  });

  if (radiusKm && radiusKm > 0) {
    return withDistances.filter((m) => m.distanceKm <= radiusKm).sort((a, b) => a.distanceKm - b.distanceKm);
  }

  return withDistances.sort((a, b) => a.distanceKm - b.distanceKm);
}

/**
 * Audit helper returning breakdown by radius bands from a reference district.
 */
export function getMandiRadiusCoverage(nearDistrict: string = "Kurnool") {
  const mandis = getMandis({ nearDistrict, state: "all", radiusKm: null });
  return {
    band0_50: mandis.filter((m) => m.distanceKm <= 50),
    band50_100: mandis.filter((m) => m.distanceKm > 50 && m.distanceKm <= 100),
    band100_150: mandis.filter((m) => m.distanceKm > 100 && m.distanceKm <= 150),
    band150_250: mandis.filter((m) => m.distanceKm > 150 && m.distanceKm <= 250),
    band250Plus: mandis.filter((m) => m.distanceKm > 250),
    total: mandis.length,
  };
}
